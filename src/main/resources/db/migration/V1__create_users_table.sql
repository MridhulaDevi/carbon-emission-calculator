CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    gender VARCHAR(255),
    age INTEGER,
    role VARCHAR(255),
    preferred_transport VARCHAR(255),
    diet_preference VARCHAR(255),
    energy_source VARCHAR(255),
    sustainability_goal VARCHAR(255)
);